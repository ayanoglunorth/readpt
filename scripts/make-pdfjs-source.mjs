// Writes src/pdf/pdfjsSource.ts: pdf.js (Apache-2.0) and its worker as strings, so a WebView or iframe can run them offline.
// Usage: node scripts/make-pdfjs-source.mjs   (needs pdfjs-dist 3.11.174 in node_modules)
import fs from 'node:fs';
const b = 'node_modules/pdfjs-dist/build/';
const safe = s => JSON.stringify(s.replace(/<\/script/gi, '<\/script'));
fs.writeFileSync('src/pdf/pdfjsSource.ts', `// GENERATED by scripts/make-pdfjs-source.mjs. Do not edit. pdf.js 3.11.174, Apache-2.0.
export const PDFJS: string = ${safe(fs.readFileSync(b + 'pdf.min.js', 'utf8'))};
export const PDFJS_WORKER: string = ${safe(fs.readFileSync(b + 'pdf.worker.min.js', 'utf8'))};
`);
