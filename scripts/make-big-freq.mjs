// One-off generator for engine/freq-big.js.
// Usage: node scripts/make-big-freq.js en_50k.txt enable1.txt
// Sources: hermitdave/FrequencyWords en_50k.txt (OpenSubtitles 2018; content CC-BY-SA-4.0, code MIT) and the ENABLE word list
// (public domain). A word is kept only when ENABLE lists it, which drops names and typos; inflections fold into their base.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import '../engine/words-en.js';
import '../engine/freq-en.js';
import DS from '../engine/vocab.js';

const [freqFile, enableFile] = process.argv.slice(2);
const enable = new Set(fs.readFileSync(enableFile, 'utf8').split(/\r?\n/).filter(Boolean));
const listed = new Set(Object.values(DS.WORDS_EN).flatMap(l => l.split(' ')));
const counts = new Map();
for (const line of fs.readFileSync(freqFile, 'utf8').split(/\r?\n/)) {
  const [word, n] = line.split(' ');
  if (/^[a-z]{2,}$/.test(word || '') && enable.has(word)) counts.set(word, Number(n));
}
const total = new Map();
for (const [w, n] of counts) {
  // A CEFR-listed word counts as itself ("thing" must not fold into "th"). shortcut: a wrong base (news -> new) only lowers the level.
  const base = listed.has(w) ? null : DS.baseForms(w, false).find(b => b !== w && counts.has(b));
  const key = base || w;
  total.set(key, (total.get(key) || 0) + n);
}
const words = [...total].sort((a, b) => b[1] - a[1]).map(([w]) => w);

// Looptions' rank cuts count CEFR headwords only; find the same words in this longer list.
const CUTS = [800, 1800, 3000, 4500, 6500];
const cefrOrder = DS.FREQ_EN.split(' ');
const cuts = CUTS.map(c => words.indexOf(cefrOrder[c - 1]) + 1);
if (cuts.some(c => c <= 0) || cuts.some((c, i) => i && c <= cuts[i - 1])) throw new Error('bad cuts ' + cuts);

fs.writeFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), '../engine/freq-big.js'), `// GENERATED by scripts/make-big-freq.js. Do not edit.
// Word order from hermitdave/FrequencyWords (OpenSubtitles 2018, CC-BY-SA-4.0), restricted to ENABLE words (public domain); most frequent first.
import { DS } from './ds.js';

DS.BIG_EN = ${JSON.stringify(words.join(' '))};
DS.BIG_CUTS = ${JSON.stringify(cuts)}; // 1-based BIG_EN rank where A2, B1, B2, C1, C2 start
export default DS;
`);
console.log(words.length, 'words; cuts', cuts.join(' '), '; first', words.slice(0, 8).join(' '));
